import assert from 'node:assert/strict';
import fs from 'node:fs';
import {withRiverBaselines,sortRivers} from '../river-insights.js';
import {skyConditions,nightLightAt,forecastAt,tonightTimes} from '../sky-quality.js';
const read=file=>JSON.parse(fs.readFileSync(new URL('../'+file,import.meta.url)));
const base=read('river-baselines.json'),names=read('river-stations.json'),grid=read('sky-lights.json');
assert(Object.keys(base.baselines).length>=Object.keys(names).length*.7);
assert(Object.values(base.baselines).every(x=>x.days>=20&&Number.isFinite(x.meanFt)));
assert(grid.cells.filter(c=>Number.isFinite(c[2])).length>=grid.cells.length*.7);
assert(grid.cells.every(c=>c[2]===null||c[2]>=0&&c[2]<=38.2));
const now=Date.parse('2026-11-15T19:00:00Z');
const snapshot={checkedAt:'2026-11-15T18:00:00Z',expiresAt:'2026-11-18T18:00:00Z',baselines:{a:{meanFt:-3,days:30},b:{meanFt:10,days:30}}};
const live={features:[{geometry:{coordinates:[-90.4,38.63]},properties:{id:'USGS-a',title:'USGS-a · -2.5 ft'}},{geometry:{coordinates:[-90.3,38.6]},properties:{id:'USGS-b',title:'USGS-b · 8 ft'}}]};
const result=withRiverBaselines(live,{a:{name:'Meramec River',drainageSqMi:3000},b:{name:'Mississippi River',drainageSqMi:600000}},snapshot,now);
assert.equal(result.riverComparison.compared,2);assert.equal(result.features[0].properties.deviationFt,.5);assert.equal(result.features[1].properties.deviationFt,-2);
assert.equal(sortRivers(result.features,[-90.4,38.63])[0].properties.id,'USGS-b');
assert.equal(live.features.some(f=>'deviationFt' in f.properties),false);
assert.equal(withRiverBaselines(live,{},snapshot,Date.parse(snapshot.expiresAt)+1).riverComparison.compared,0);
assert.equal(nightLightAt(grid,42,-90),null);
const rad=nightLightAt(grid,38.67,-90.39,Date.parse(grid.checkedAt)+1000);assert(Number.isFinite(rad));
const t=Date.parse('2026-11-16T04:00:00Z');
const at=(cloud,radiance,time=t)=>skyConditions({time,lat:38.67,lng:-90.39,cloudCoverPct:cloud,radiance});
assert.equal(at(100,rad).score,0);assert(at(0,rad).score>at(80,rad).score);assert(at(0,.1).score>at(0,30).score);
assert.equal(at(0,null).score,null);assert.equal(at(0,0,Date.parse('2026-11-15T18:00:00Z')).score,0);
assert.equal(forecastAt([{time:'2026-11-16T01:00:00Z',cloudCoverPct:0}],Date.parse('2026-11-16T01:30:00Z')).cloudCoverPct,0);
assert.equal(forecastAt([{time:'2026-11-16T01:00:00Z',cloudCoverPct:0}],Date.parse('2026-11-16T03:30:00Z')),undefined);
assert(tonightTimes({darknessStart:'2026-11-16T00:22:00Z',darknessEnd:'2026-11-16T11:14:00Z'},now).length>5);
console.log('PASS: river datum/negative-height comparisons, ordering, name enrichment, expiry; satellite saturation bounds, clear/overcast/darkness/daylight, missing data and forecast windows.');
