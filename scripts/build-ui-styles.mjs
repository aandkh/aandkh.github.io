// Concatenate maintained styles in their original cascade order. No minifier,
// selector rewriting, omitted rules or runtime injection. Keep source CSS editable.
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const files=JSON.parse(fs.readFileSync(path.join(root,'ui-styles.json'),'utf8'));
if(!Array.isArray(files)||new Set(files).size!==files.length)throw Error('Invalid style manifest');
const output='/* Generated by node scripts/build-ui-styles.mjs. Edit source styles, then rebuild. */\n'+files.map(name=>{
 if(!/^(?:vendor\/maplibre-gl|[a-z][a-z0-9-]*)\.css$/.test(name))throw Error('Invalid CSS path');
 const css=fs.readFileSync(path.join(root,name),'utf8');
 if(/@import\b|@charset\b/i.test(css))throw Error(name+': imports/charsets require explicit handling');
 // Root CSS keeps URL bases; bundled MapLibre CSS contains only inline data URLs.
 if(name.startsWith('vendor/') && [...css.matchAll(/url\(["']?([^\)]+)/g)].some(m=>!m[1].startsWith('data:')))throw Error('Vendor style has a relative URL');
 return '\n/* '+name+' */\n'+css;
}).join('\n');
const dest=path.join(root,'ui-bundle.css');
if(process.argv.includes('--check')){
 if(fs.readFileSync(dest,'utf8')!==output)throw Error('ui-bundle.css is stale; run node scripts/build-ui-styles.mjs');
 console.log('PASS: '+files.length+' stylesheet sources match the deployed bundle in cascade order');
}else{fs.writeFileSync(dest,output);console.log('Built '+files.length+' styles into '+Buffer.byteLength(output)+' bytes');}
